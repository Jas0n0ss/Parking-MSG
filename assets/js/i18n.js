  function normalizeSite(lang) {
    return String(lang || '').toLowerCase().indexOf('en') === 0 ? 'en' : 'zh';
  }

  function currentSiteLang() {
    var attr = document.documentElement.getAttribute('data-ui-lang');
    if (attr === 'en' || attr === 'zh') return attr;
    try {
      var raw = window.localStorage.getItem('carmsg:ui-lang');
      var stored = raw;
      if (raw) {
        try { stored = JSON.parse(raw); } catch (error) { stored = raw; }
      }
      if (stored === 'en' || stored === 'zh') return stored;
    } catch (error) {
      /* ignore */
    }
    return 'zh';
  }

  function uiText(key, vars) {
    var lang = currentSiteLang();
    var table = UI[lang] || UI.zh;
    var value = table[key];
    if (value === undefined) value = UI.zh[key];
    if (value === undefined) return key;
    if (!vars) return value;
    return value.replace(/\{(\w+)\}/g, function (match, name) {
      return vars[name] === undefined ? match : String(vars[name]);
    });
  }

  function applyUI(lang, root) {
    if (lang && lang.nodeType) {
      root = lang;
      lang = null;
    }
    var scope = root || document;
    var code = lang ? normalizeSite(lang) : currentSiteLang();
    var nodes = scope.querySelectorAll('[data-ui]');
    Array.prototype.forEach.call(nodes, function (el) {
      var key = el.getAttribute('data-ui');
      var table = UI[code] || UI.zh;
      var value = table[key];
      if (value === undefined) value = UI.zh[key];
      if (value !== undefined) el.textContent = value;
    });
    var attrs = scope.querySelectorAll('[data-ui-aria-label], [data-ui-title], [data-ui-placeholder]');
    Array.prototype.forEach.call(attrs, function (el) {
      for (var i = 0; i < el.attributes.length; i += 1) {
        var attr = el.attributes[i];
        if (attr.name.indexOf('data-ui-') !== 0) continue;
        var target = attr.name.slice('data-ui-'.length);
        if (!target) continue;
        var table = UI[code] || UI.zh;
        var value = table[attr.value];
        if (value === undefined) value = UI.zh[attr.value];
        if (value !== undefined) el.setAttribute(target, value);
      }
    });
  }

  var SUPPORTED = {};
  LANGS.forEach(function (item) { SUPPORTED[item.code] = true; });

  function normalizeLang(code) {
    if (!code) return null;
    var value = String(code).trim().toLowerCase().replace(/_/g, '-');
    if (!value) return null;
    if (value === 'auto') return 'auto';
    if (value === 'zh' || value.indexOf('zh-hans') === 0 || value.indexOf('zh-cn') === 0 ||
        value.indexOf('zh-sg') === 0 || value.indexOf('zh-my') === 0) {
      return 'zh-Hans';
    }
    if (value.indexOf('zh-') === 0) return 'zh-Hant';
    if (value.indexOf('ja') === 0) return 'ja';
    if (value.indexOf('ko') === 0) return 'ko';
    if (value.indexOf('de') === 0) return 'de';
    if (value.indexOf('fr') === 0) return 'fr';
    if (value.indexOf('es') === 0) return 'es';
    if (value.indexOf('pt') === 0) return 'pt';
    if (value.indexOf('it') === 0) return 'it';
    if (value.indexOf('ru') === 0) return 'ru';
    if (value.indexOf('en') === 0) return 'en';
    return null;
  }

  function resolve(setting, plateCountry) {
    var requested = normalizeLang(setting);
    if (requested && requested !== 'auto') return requested;
    if (requested !== 'auto') return 'en';
    var country = (window.CM_COUNTRY_MAP || {})[plateCountry || 'CN'];
    var auto = country && normalizeLang(country.lang);
    return auto && auto !== 'auto' ? auto : 'en';
  }

  function t(lang, key, vars) {
    var code = normalizeLang(lang) || 'en';
    var table = DICT[code] || DICT.en;
    var value = table[key];
    if (value === undefined) value = DICT.en[key];
    if (value === undefined) return key;
    if (!vars) return value;
    return value.replace(/\{(\w+)\}/g, function (match, name) {
      return vars[name] === undefined ? match : String(vars[name]);
    });
  }

  function translateAttributes(el, code) {
    for (var i = 0; i < el.attributes.length; i += 1) {
      var attr = el.attributes[i];
      if (attr.name.indexOf('data-i18n-') !== 0) continue;
      var target = attr.name.slice('data-i18n-'.length);
      if (!target) continue;
      el.setAttribute(target, t(code, attr.value));
    }
  }

  function apply(lang, root) {
    var code = normalizeLang(lang) || 'en';
    var scope = root || document;
    var nodes = scope.querySelectorAll('[data-i18n]');
    Array.prototype.forEach.call(nodes, function (el) {
      el.textContent = t(code, el.getAttribute('data-i18n'));
    });
    var attrs = scope.querySelectorAll('[data-i18n-aria-label], [data-i18n-title], [data-i18n-placeholder]');
    Array.prototype.forEach.call(attrs, function (el) {
      translateAttributes(el, code);
    });
  }

  function countryName(code, lang) {
    var country = (window.CM_COUNTRY_MAP || {})[code];
    if (!country) return code || '';
    var normalized = normalizeLang(lang);
    if (normalized === 'zh-Hans' || normalized === 'zh-Hant') return country.zh;
    return country.name;
  }

  function isSupported(code) {
    return !!SUPPORTED[normalizeLang(code)];
  }

  window.CarMsgI18N = {
    langs: LANGS,
    normalize: normalizeLang,
    resolve: resolve,
    t: t,
    apply: apply,
    ui: uiText,
    applyUI: applyUI,
    siteLang: currentSiteLang,
    normalizeSite: normalizeSite,
    countryName: countryName,
    isSupported: isSupported
  };
